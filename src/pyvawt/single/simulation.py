@nb.njit(fastmath=True, cache=True)
def _radialforce_kernel(
    uvec: np.ndarray,
    vvec: np.ndarray,
    thetavec: np.ndarray,
    r: float,
    chord: float,
    twist: float,
    delta: float,
    B: int,
    Omega: float,
    solidity: float,
    Vinf: float,
    rho: float,
    mu: float,
    alpha_grid: np.ndarray,
    W_grid: np.ndarray,
    cl_table: np.ndarray,
    cd_table: np.ndarray,
    use_dynamic_stall: bool,
    aoa_stall_pos: float,
    aoa_stall_neg: float,
    AOA0: float,
    tc: float,
    use_tip_loss: bool = False,
    z: float = 0.0,
    H: float = 0.0,
) -> tuple[
    np.ndarray,
    float,
    float,
    float,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:
    """
    Execute high-density aerodynamic kernel for VAWT blade element calculations.

    Computes velocity triangles, static/dynamic lift and drag coefficients, 
    instantaneous force decompositions, integrated thrust/power coefficients,
    and induction correction factors over an azimuthal revolution.

    Parameters
    ----------
    uvec : np.ndarray
        1D array of axial induction factor distribution along azimuth [-].
    vvec : np.ndarray
        1D array of tangential induction factor distribution along azimuth [-].
    thetavec : np.ndarray
        1D array of azimuthal angles [rad].
    r : float
        Rotor radius [m].
    chord : float
        Blade chord length [m].
    twist : float
        Blade pitch/twist angle [rad].
    delta : float
        Cone/blade inclination angle [rad].
    B : int
        Number of blades [-].
    Omega : float
        Rotor angular rotational speed [rad/s].
    solidity : float
        Target rotor solidity [-].
    Vinf : float
        Freestream wind speed [m/s].
    rho : float
        Air density [kg/m³].
    mu : float
        Dynamic air viscosity [Pa·s].
    alpha_grid : np.ndarray
        1D grid array for angle of attack LUT lookup [rad].
    W_grid : np.ndarray
        1D grid array for relative velocity LUT lookup [m/s].
    cl_table : np.ndarray
        2D matrix of precomputed static lift coefficients [-].
    cd_table : np.ndarray
        2D matrix of precomputed static drag coefficients [-].
    use_dynamic_stall : bool
        Flag indicating whether to apply the Boeing-Vertol dynamic stall model.
    aoa_stall_pos : float
        Positive static stall angle of attack [rad].
    aoa_stall_neg : float
        Negative static stall angle of attack [rad].
    AOA0 : float
        Zero-lift angle of attack [rad].
    tc : float
        Airfoil relative thickness-to-chord ratio [-].

    Returns
    -------
    q : np.ndarray
        Azimuthal distribution of normal force loading parameter [-].
    ka : float
        Induction correction factor [-].
    CT : float
        Integrated rotor thrust coefficient [-].
    CP : float
        Integrated rotor power coefficient [-].
    Rp : np.ndarray
        Normal/radial force per unit span distribution along azimuth [N/m].
    Tp : np.ndarray
        Tangential force per unit span distribution along azimuth [N/m].
    Zp : np.ndarray
        Vertical/spanwise force per unit span distribution along azimuth [N/m].
    alpha : np.ndarray
        Distribution of local angle of attack along azimuth [rad].
    W : np.ndarray
        Distribution of local relative flow velocity along azimuth [m/s].
    """
    n = len(thetavec)
    dtheta = thetavec[1] - thetavec[0] if n > 1 else 0.0
    rotation = 1.0 if Omega >= 0.0 else -1.0
    abs_Omega = abs(Omega)

    # Pre-allocate output buffers to prevent dynamic heap allocation in execution loops
    W = np.empty(n, dtype=np.float64)
    phi = np.empty(n, dtype=np.float64)
    alpha = np.empty(n, dtype=np.float64)
    cl = np.empty(n, dtype=np.float64)
    cd = np.empty(n, dtype=np.float64)
    cm = np.zeros(n, dtype=np.float64)

    # 1. Compute Velocity Triangles and Static Coefficients in a single fused loop
    for i in range(n):
        sin_t = np.sin(thetavec[i])
        cos_t = np.cos(thetavec[i])
        u_val = uvec[i]
        v_val = vvec[i]

        Vn = Vinf * (1.0 + u_val) * sin_t - Vinf * v_val * cos_t
        Vt = rotation * (Vinf * (1.0 + u_val) * cos_t + Vinf * v_val * sin_t) + abs_Omega * r

        w_val = np.sqrt(Vn * Vn + Vt * Vt)
        phi_val = np.arctan2(Vn, Vt)
        alpha_val = phi_val - twist

        W[i] = w_val
        phi[i] = phi_val
        alpha[i] = alpha_val

        # Direct 2D LUT interpolation
        cl[i] = interp2d_scalar(alpha_val, w_val, alpha_grid, W_grid, cl_table)
        cd[i] = interp2d_scalar(alpha_val, w_val, alpha_grid, W_grid, cd_table)

    # 2. Dynamic Stall Model (Boeing-Vertol)
    if use_dynamic_stall:
        dt = dtheta / abs_Omega if abs_Omega > 1e-6 else 1.0
        flagL = 0
        flagD = 0

        for i in range(n):
            i_prev = n - 1 if i == 0 else i - 1
            dalpha_dt = (alpha[i] - alpha[i_prev]) / dt
            w_val = W[i] if W[i] > 1e-6 else 1e-6
            adotnorm = (dalpha_dt * chord) / (2.0 * w_val)
            umach = w_val / 343.0

            c_l, c_d, c_m, flagL, flagD = boeing_vertol_jit(
                cl[i],
                cd[i],
                cm[i],
                alpha[i],
                adotnorm,
                umach,
                w_val,
                aoa_stall_pos,
                aoa_stall_neg,
                AOA0,
                tc,
                flagL,
                flagD,
                alpha_grid,
                W_grid,
                cl_table,
                cd_table,
            )
            cl[i] = c_l
            cd[i] = c_d
            cm[i] = c_m

    # 3. Geometric Rotor Parameters & Solidity Evaluation
    sigma_r = B * chord / r
    sigma_D = B * chord / (2.0 * r)
    sigma = (
        sigma_r
        if abs(solidity - sigma_r) < abs(solidity - sigma_D)
        else 2.0 * solidity
    )

    cos_delta = np.cos(delta)
    tan_delta = np.tan(delta)

    # 4. Uncorrected Normal and Tangential Coefficients
    cn = np.empty(n, dtype=np.float64)
    ct = np.empty(n, dtype=np.float64)

    for i in range(n):
        c_phi = np.cos(phi[i])
        s_phi = np.sin(phi[i])
        cn[i] = cl[i] * c_phi + cd[i] * s_phi
        ct[i] = cl[i] * s_phi - cd[i] * c_phi

    # 4b. Apply Tip-Loss Correction (if enabled)
    if use_tip_loss and H > 1e-6:
        cn, ct, _ = apply_tip_loss(cn, ct, z, H, B, Omega, r, Vinf)

    # 4c. Fused Force Decomposition Loop
    q = np.empty(n, dtype=np.float64)
    Rp = np.empty(n, dtype=np.float64)
    Tp = np.empty(n, dtype=np.float64)
    Zp = np.empty(n, dtype=np.float64)
    integrand = np.empty(n, dtype=np.float64)

    inv_Vinf = 1.0 / Vinf if Vinf != 0.0 else 0.0
    half_rho = 0.5 * rho

    for i in range(n):
        cn_i = cn[i]
        ct_i = ct[i]

        w_ratio = W[i] * inv_Vinf
        q[i] = (sigma / (4.0 * np.pi)) * cn_i * (w_ratio * w_ratio)

        qdyn = half_rho * W[i] * W[i]
        Rp[i] = -cn_i * qdyn * chord
        Tp[i] = ct_i * qdyn * chord / cos_delta
        Zp[i] = -cn_i * qdyn * chord * tan_delta

        sin_t = np.sin(thetavec[i])
        cos_t = np.cos(thetavec[i])
        integrand[i] = (w_ratio * w_ratio) * (
            cn_i * sin_t - rotation * ct_i * cos_t / cos_delta
        )

    # 5. Integrated Rotor Performance Factors (CT & ka)
    CT = (sigma / (4.0 * np.pi)) * fast_trapz(integrand, thetavec)

    if CT > 2.0:
        a = 0.5 * (1.0 + np.sqrt(1.0 + CT))
        ka = 1.0 / (a - 1.0)
    elif CT > 0.96:
        a = (1.0 / 7.0) * (1.0 + 3.0 * np.sqrt(3.5 * CT - 3.0))
        ka = 18.0 * a / (7.0 * a**2 - 2.0 * a + 4.0)
    else:
        a = 0.5 * (1.0 - np.sqrt(1.0 - CT))
        ka = 1.0 / (1.0 - a)

    # Integrated Power Coefficient (CP)
    P = abs_Omega * B / (2.0 * np.pi) * fast_trapz(r * Tp, thetavec)
    CP = P / (0.5 * rho * (Vinf * Vinf * Vinf) * (2.0 * r))

    return q, ka, CT, CP, Rp, Tp, Zp, alpha, W

