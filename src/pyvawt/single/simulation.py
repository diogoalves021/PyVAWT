@nb.njit(fastmath=True, inline="always")
def Dxintegrand(x: float, y: float, phi: float) -> float:
    """
    Evaluate the kernel integrand for the x-component of velocity influence (Dx).

    Calculates the induced velocity contribution in the x-direction per unit panel
    length at control point (x, y) generated by an elemental source/vortex panel
    at azimuthal angle phi.

    Parameters
    ----------
    x : float
        Normalized x-coordinate of the target control point [-].
    y : float
        Normalized y-coordinate of the target control point [-].
    phi : float
        Azimuthal panel angle along the rotor perimeter [rad].

    Returns
    -------
    float
        Evaluated integrand value for the Dx influence coefficient [-].
    """
    v1 = x + np.sin(phi)
    v2 = y - np.cos(phi)
    return (v1 * np.sin(phi) - v2 * np.cos(phi)) / (2.0 * np.pi * (v1 * v1 + v2 * v2))

@nb.njit(fastmath=True, inline="always")
def Ayintegrand(x: float, y: float, phi: float) -> float:
    """
    Evaluate the kernel integrand for the y-component of velocity influence (Ay).

    Calculates the induced velocity contribution in the y-direction per unit panel
    length at control point (x, y) generated by an elemental source/vortex panel
    at azimuthal angle phi. Includes singularity protection for co-located points.

    Parameters
    ----------
    x : float
        Normalized x-coordinate of the target control point [-].
    y : float
        Normalized y-coordinate of the target control point [-].
    phi : float
        Azimuthal panel angle along the rotor perimeter [rad].

    Returns
    -------
    float
        Evaluated integrand value for the Ay influence coefficient [-].
    """
    v1 = x + np.sin(phi)
    v2 = y - np.cos(phi)
    if abs(v1) < 1e-12 and abs(v2) < 1e-12:
        return 0.0
    return (v1 * np.cos(phi) + v2 * np.sin(phi)) / (2.0 * np.pi * (v1 * v1 + v2 * v2))

