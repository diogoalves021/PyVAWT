@nb.njit(fastmath=True, cache=True)
def DxIJ(
    xvec: np.ndarray,
    yvec: np.ndarray,
    thetavec: np.ndarray,
    n_substeps: int = 16,
) -> np.ndarray:
    """
    Compute the x-direction influence coefficient matrix (DxIJ) via panel integration.

    Integrates the Dx kernel (`Dxintegrand`) across discretized azimuthal panel
    bounds using a C-compiled Composite Trapezoidal rule. Direct function call
    inlining bypasses function-pointer overhead for maximum execution speed.

    Parameters
    ----------
    xvec : np.ndarray
        1D array of control point x-coordinates [-].
    yvec : np.ndarray
        1D array of control point y-coordinates [-].
    thetavec : np.ndarray
        1D array of panel discretization azimuthal angles [rad].
    n_substeps : int, default=16
        Number of numerical integration sub-intervals per panel [-].

    Returns
    -------
    np.ndarray of shape (len(xvec), len(thetavec))
        Assembled influence coefficient matrix for velocity induced in the x-direction.
    """
    nx = len(xvec)
    ntheta = len(thetavec)
    dtheta = thetavec[1] - thetavec[0]
    A = np.zeros((nx, ntheta), dtype=np.float64)

    for i in range(nx):
        x = xvec[i]
        y = yvec[i]
        for j in range(ntheta):
            a = thetavec[j] - dtheta / 2.0
            b = thetavec[j] + dtheta / 2.0
            h = (b - a) / n_substeps

            # Direct inlined kernel evaluation over composite trapezoidal sub-steps
            sum_val = 0.5 * (Dxintegrand(x, y, a) + Dxintegrand(x, y, b))
            for k in range(1, n_substeps):
                sum_val += Dxintegrand(x, y, a + k * h)

            A[i, j] = sum_val * h

    return A

@nb.njit(fastmath=True, cache=True)
def AyIJ(
    xvec: np.ndarray,
    yvec: np.ndarray,
    thetavec: np.ndarray,
    n_substeps: int = 16,
) -> np.ndarray:
    """
    Compute the y-direction influence coefficient matrix (AyIJ) via panel integration.

    Integrates the Ay kernel (`Ayintegrand`) across discretized azimuthal panel
    bounds using a C-compiled Composite Trapezoidal rule. Direct function call
    inlining bypasses function-pointer overhead for maximum execution speed.

    Parameters
    ----------
    xvec : np.ndarray
        1D array of control point x-coordinates [-].
    yvec : np.ndarray
        1D array of control point y-coordinates [-].
    thetavec : np.ndarray
        1D array of panel discretization azimuthal angles [rad].
    n_substeps : int, default=16
        Number of numerical integration sub-intervals per panel [-].

    Returns
    -------
    np.ndarray of shape (len(xvec), len(thetavec))
        Assembled influence coefficient matrix for velocity induced in the y-direction.
    """
    nx = len(xvec)
    ntheta = len(thetavec)
    dtheta = thetavec[1] - thetavec[0]
    A = np.zeros((nx, ntheta), dtype=np.float64)

    for i in range(nx):
        x = xvec[i]
        y = yvec[i]
        for j in range(ntheta):
            a = thetavec[j] - dtheta / 2.0
            b = thetavec[j] + dtheta / 2.0
            h = (b - a) / n_substeps

            # Direct inlined kernel evaluation over composite trapezoidal sub-steps
            sum_val = 0.5 * (Ayintegrand(x, y, a) + Ayintegrand(x, y, b))
            for k in range(1, n_substeps):
                sum_val += Ayintegrand(x, y, a + k * h)

            A[i, j] = sum_val * h

    return A

@nb.njit(fastmath=True, cache=True)
def WxIJ(xvec: np.ndarray, yvec: np.ndarray, thetavec: np.ndarray) -> np.ndarray:
    """
    Compute the wake influence matrix (WxIJ) for external control points.

    Evaluates whether target control points lie within the geometric trailing wake
    region and assigns corresponding wake influence coefficients based on the
    azimuthal position of the panels.

    Parameters
    ----------
    xvec : np.ndarray
        1D array of target control point x-coordinates [-].
    yvec : np.ndarray
        1D array of target control point y-coordinates [-].
    thetavec : np.ndarray
        1D array of panel discretization azimuthal angles [rad].

    Returns
    -------
    np.ndarray of shape (len(xvec), len(thetavec))
        Assembled wake influence coefficient matrix (WxIJ).
    """
    nx = len(xvec)
    ntheta = len(thetavec)
    dtheta = thetavec[1] - thetavec[0]
    Wx = np.zeros((nx, ntheta), dtype=np.float64)

    # Precompute midpoint array once outside the loop to prevent redundant allocations
    theta_mid = thetavec + dtheta / 2.0

    for i in range(nx):
        x = xvec[i]
        y = yvec[i]

        # Check if control point lies within the geometric wake domain
        if -1.0 <= y <= 1.0 and x >= 0.0 and (x * x + y * y) >= 1.0:
            thetak = np.arccos(y)
            k = np.searchsorted(theta_mid, thetak, side="right")
            if 0 <= k < ntheta:
                Wx[i, k] = -1.0
                Wx[i, ntheta - k - 1] = 1.0

    return Wx

@nb.njit(fastmath=True, cache=True)
def DxII(thetavec: np.ndarray) -> np.ndarray:
    """
    Compute the self-influence matrix (DxII) for a turbine's own perimeter.

    Constructs the self-induction influence matrix in the x-direction based on
    the angular discretization of the turbine perimeter.

    Parameters
    ----------
    thetavec : np.ndarray
        1D array of panel discretization azimuthal angles [rad].

    Returns
    -------
    np.ndarray of shape (len(thetavec), len(thetavec))
        Assembled self-influence matrix (DxII) in the x-direction.
    """
    ntheta = len(thetavec)
    dtheta = thetavec[1] - thetavec[0]
    Rx = (dtheta / (4.0 * np.pi)) * np.ones((ntheta, ntheta), dtype=np.float64)

    for i in range(ntheta):
        if i < ntheta // 2:
            Rx[i, i] = (-1.0 + 1.0 / ntheta) / 2.0
        else:
            Rx[i, i] = (1.0 + 1.0 / ntheta) / 2.0

    return Rx


@nb.njit(fastmath=True, cache=True)
def WxII(thetavec: np.ndarray) -> np.ndarray:
    """
    Compute the self-wake influence matrix (WxII) for a turbine's own perimeter.

    Populates symmetric wake self-influence terms across paired panel indices
    along the downstream half of the turbine perimeter.

    Parameters
    ----------
    thetavec : np.ndarray
        1D array of panel discretization azimuthal angles [rad].

    Returns
    -------
    np.ndarray of shape (len(thetavec), len(thetavec))
        Assembled self-wake influence matrix (WxII).
    """
    ntheta = len(thetavec)
    Wx = np.zeros((ntheta, ntheta), dtype=np.float64)

    for i in range(ntheta // 2, ntheta):
        Wx[i, ntheta - 1 - i] = -1.0

    return Wx

def precomputeMatrices(ntheta, modulepath):
    '''
    Precompute matrices for self-influence and save them in an HDF5 file.

    Parameters
    ----------
    ntheta : int
        Number of angular divisions (theta).
    modulepath : str
        Path to the directory where the HDF5 file will be saved.

    Returns
    -------
    filepath : str
        Path to the saved HDF5 file containing the precomputed matrices.

    Notes
    -----
    The function computes the self-influence matrices for Dx, Wx, and Ay, 
    then stores them in an HDF5 file for future use.
    '''
    dtheta = 2 * np.pi / ntheta
    theta = np.arange(dtheta / 2, 2 * np.pi, dtheta)

    # Precompute matrices
    Dxself = DxII(theta)
    Wxself = WxII(theta)
    Ayself = AyIJ(-np.sin(theta), np.cos(theta), theta)

    filepath = f'{modulepath}/theta-{ntheta}.h5'
    with h5py.File(filepath, 'w') as file:
        file.create_dataset('theta', data=theta)
        file.create_dataset('Dx', data=Dxself)
        file.create_dataset('Wx', data=Wxself)
        file.create_dataset('Ay', data=Ayself)

    return filepath

def matrixAssemble(
    centerX: float, centerY: float, radius: float, ntheta: int
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Assemble the influence matrices for a single VAWT turbine with RAM caching.

    Loads or computes self-influence matrices (Dx, Wx, Ay) for a single turbine
    based on the number of angular discretization points, utilizing an in-memory
    cache to eliminate redundant disk I/O operations.

    Parameters
    ----------
    centerX : float
        X-coordinate of the turbine center [m].
    centerY : float
        Y-coordinate of the turbine center [m].
    radius : float
        Radius of the turbine [m].
    ntheta : int
        Number of angular divisions (discretization steps along the perimeter).

    Returns
    -------
    Ax : np.ndarray of shape (ntheta, ntheta)
        Assembled matrix combining self-induction and wake influence in the x-direction.
    Ay : np.ndarray of shape (ntheta, ntheta)
        Assembled matrix capturing self-induction influence in the y-direction.
    theta : np.ndarray of shape (ntheta,)
        Array of azimuthal angles along the circular path [rad].

    Notes
    -----
    This function is tailored for single vertical-axis wind turbine (VAWT) simulations.
    Precomputed matrices are cached in RAM (`_MATRIX_H5_CACHE`) after the initial disk read
    from HDF5, bypassing disk read latency on subsequent solver calls.
    """
    modulepath = os.getcwd()
    cache_key = (ntheta, modulepath)

    # If the data was previously loaded, return arrays directly from RAM
    if cache_key in _MATRIX_H5_CACHE:
        Ax_cached, Ay_cached, theta_cached = _MATRIX_H5_CACHE[cache_key]
        # Return copies (.copy()) to ensure downstream array modifications
        # do not corrupt the cached reference in RAM
        return Ax_cached.copy(), Ay_cached.copy(), theta_cached.copy()

    # DISK READ (Executed on first call only)
    file = f"theta-{ntheta}.h5"
    filepath = os.path.join(modulepath, file)

    if not os.path.isfile(filepath):
        filepath = precomputeMatrices(ntheta, modulepath)

    # Load precomputed datasets from HDF5 file
    with h5py.File(filepath, "r") as f:
        theta = f["theta"][:]
        Dxself = f["Dx"][:]
        Wxself = f["Wx"][:]
        Ayself = f["Ay"][:]

    # Assemble Ax and Ay influence matrices
    Ax = Dxself + Wxself
    Ay = Ayself.copy()

    # Store base matrices in RAM for subsequent solver iterations
    _MATRIX_H5_CACHE[cache_key] = (Ax, Ay, theta)

    return Ax.copy(), Ay.copy(), theta.copy()

