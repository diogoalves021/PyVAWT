@nb.njit(fastmath=True, cache=True)
def _residual_kernel(
    w: np.ndarray,
    A: np.ndarray,
    thetavec: np.ndarray,
    r: float,
    chord: float,
    twist: float,
    delta: float,
    B: int,
    Omega: float,
    solidity: float,
    Vinf: float,
    rho: float,
    mu: float,
    alpha_grid: np.ndarray,
    W_grid: np.ndarray,
    cl_table: np.ndarray,
    cd_table: np.ndarray,
    use_dynamic_stall: bool,
    aoa_stall_pos: float,
    aoa_stall_neg: float,
    AOA0: float,
    tc: float,
) -> np.ndarray:
    """
    Compute actuator-cylinder system residual vector entirely in C via Numba.

    Calculates normal induction loading parameter q and scalar induction factor ka
    via direct dispatch to `_radialforce_kernel`, evaluating the matrix residual
    equation: R = (A @ q) * ka - w.

    Parameters
    ----------
    w : np.ndarray of shape (2 * ntheta,)
        Current solution guess vector [u_0..u_{n-1}, v_0..v_{n-1}].
    A : np.ndarray of shape (2 * ntheta, ntheta)
        Combined aerodynamic influence matrix [Ax; Ay].
    thetavec : np.ndarray
        1D array of azimuthal discretization angles [rad].
    r, chord, twist, delta, B, Omega, solidity : numeric primitives
        Turbine geometric and operational parameters.
    Vinf, rho, mu : numeric primitives
        Fluid environment parameters.
    alpha_grid, W_grid, cl_table, cd_table : np.ndarray
        Aerodynamic polar lookup tables.
    use_dynamic_stall : bool
        Dynamic stall flag.
    aoa_stall_pos, aoa_stall_neg, AOA0, tc : float
        Airfoil aerodynamic stall bounds.

    Returns
    -------
    np.ndarray of shape (2 * ntheta,)
        Residual error vector.
    """
    ntheta = len(thetavec)
    u = w[:ntheta]
    v = w[ntheta:]

    # Direct C-level kernel call bypassing Python wrappers
    q, ka, _, _, _, _, _, _, _ = _radialforce_kernel(
        u,
        v,
        thetavec,
        r,
        chord,
        twist,
        delta,
        B,
        Omega,
        solidity,
        Vinf,
        rho,
        mu,
        alpha_grid,
        W_grid,
        cl_table,
        cd_table,
        use_dynamic_stall,
        aoa_stall_pos,
        aoa_stall_neg,
        AOA0,
        tc,
    )

    # In-place vectorized matrix-vector residual evaluation
    res = A @ q
    for i in range(2 * ntheta):
        res[i] = res[i] * ka - w[i]

    return res

